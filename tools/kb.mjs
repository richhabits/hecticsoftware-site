#!/usr/bin/env node
// Builds the assistant's knowledge sheet from the live site sources, so "Romeo" can answer anything on the site.
// Run after editing the site or tools/work.json: `node tools/kb.mjs` → api/src/kb.js (then deploy the API).
import { readFileSync, writeFileSync } from "node:fs";

const text = html => html
  .replace(/<(script|style|svg|noscript|head)[\s\S]*?<\/\1>/gi, " ")
  .replace(/<\/(h[1-6]|p|li|dt|dd|tr|section|div)>/gi, "\n").replace(/<br\s*\/?>/gi, "\n")
  .replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">")
  .split("\n").map(l => l.replace(/\s+/g, " ").trim()).filter(l => l.length > 2).join("\n");

const home = text(readFileSync("index.html", "utf8").replace(/[\s\S]*?<main/i, "<main"));
const privacy = text(readFileSync("privacy/index.html", "utf8").replace(/[\s\S]*?<main/i, "<main")).slice(0, 2500);
const work = JSON.parse(readFileSync("tools/work.json", "utf8")).map(w =>
  `- ${w.name} (${w.kind}; ${w.status}; ${w.platforms || ""}): ${w.blurb}${w.body ? " " + String(w.body).replace(/<[^>]+>/g, "").slice(0, 280) : ""}${w.link ? ` Link: ${w.link}` : ""}`).join("\n");

const kb = `SITE: https://hecticsoftware.com (home, /work/ for every project, /start/ to brief a project, /privacy/).
HOME PAGE:
${home}

ALL WORK (from the portfolio):
${work}

PRIVACY (summary of https://hecticsoftware.com/privacy/):
${privacy}`.slice(0, 16000);

writeFileSync("kb.txt", kb + "\n");
writeFileSync("api/src/kb.js", `// Generated by tools/kb.mjs from the site sources. Do not edit by hand.\nexport const KB = ${JSON.stringify(kb)};\n`);
console.log(`kb.js: ${kb.length} chars`);
